#include "LmsService.h"
#include <sqlite3.h>
#include <stdexcept>
#include <iostream>
#include <string>

namespace {
int queryInt(sqlite3* db, const char* sql) {
    sqlite3_stmt* stmt = nullptr;
    if (sqlite3_prepare_v2(db, sql, -1, &stmt, nullptr) != SQLITE_OK)
        throw std::runtime_error(sqlite3_errmsg(db));
    const int rc = sqlite3_step(stmt);
    if (rc != SQLITE_ROW) {
        sqlite3_finalize(stmt);
        throw std::runtime_error(sqlite3_errmsg(db));
    }
    const int value = sqlite3_column_int(stmt, 0);
    sqlite3_finalize(stmt);
    return value;
}
void runSql(sqlite3* db, const char* sql) {
    char* error = nullptr;
    if (sqlite3_exec(db, sql, nullptr, nullptr, &error) != SQLITE_OK) {
        std::string msg = error ? error : sqlite3_errmsg(db);
        sqlite3_free(error);
        throw std::runtime_error(msg);
    }
}
}

LmsService::LmsService(Database& database)
    : database_(database), audit_(database), notifications_(database) {}

int LmsService::scalarInt(const char* sql) { return queryInt(database_.handle(), sql); }

void LmsService::seedDemoData() {
    // Demo-only records are created once. Password hashes are generated by PasswordService
    // in a real account-registration flow; these fixed demo rows use a clearly non-production marker.
    runSql(database_.handle(), R"SQL(
      INSERT OR IGNORE INTO departments(department_id,name) VALUES(1,'Computing');
      INSERT OR IGNORE INTO courses(course_id,department_id,code,name) VALUES(1,1,'CSE101','Introduction to Computing');
      INSERT OR IGNORE INTO users(user_id,username,password_hash,role) VALUES
        (1,'demo_student','DEMO-ACCOUNT-NOT-FOR-LOGIN','Student'),
        (2,'demo_lecturer','DEMO-ACCOUNT-NOT-FOR-LOGIN','Lecturer'),
        (3,'demo_hod','DEMO-ACCOUNT-NOT-FOR-LOGIN','HeadOfDepartment'),
        (4,'demo_admin','DEMO-ACCOUNT-NOT-FOR-LOGIN','Administrator');
      INSERT OR IGNORE INTO enrolments(enrolment_id,course_id,student_user_id,status) VALUES(1,1,1,'Active');
      INSERT OR IGNORE INTO assignments(assignment_id,course_id,title,deadline,max_mark)
        VALUES(1,1,'C++ Basics Assignment','2026-10-20 23:59:59',100);
    )SQL");
}

void LmsService::runDemonstration() {
    seedDemoData();
    ConsoleNotificationObserver consoleObserver;
    notifications_.subscribe(consoleObserver);
    sqlite3* db = database_.handle();

    const int alreadyReleased = queryInt(db,
        "SELECT COUNT(*) FROM marks m JOIN submissions s ON s.submission_id=m.submission_id "
        "WHERE s.assignment_id=1 AND s.student_user_id=1 AND m.released=1;");
    if (alreadyReleased > 0) {
        std::cout << "Demo workflow was already completed. Database is persistent (lms.db).\n";
        return;
    }

    // Create submission and its first version using parameterised statements.
    sqlite3_stmt* stmt = nullptr;
    const char* insertSubmission =
        "INSERT INTO submissions(assignment_id,student_user_id,status,current_version) VALUES(1,1,'Submitted',1);";
    if (sqlite3_prepare_v2(db, insertSubmission, -1, &stmt, nullptr) != SQLITE_OK)
        throw std::runtime_error(sqlite3_errmsg(db));
    if (sqlite3_step(stmt) != SQLITE_DONE) {
        sqlite3_finalize(stmt);
        throw std::runtime_error(sqlite3_errmsg(db));
    }
    sqlite3_finalize(stmt);
    const int submissionId = static_cast<int>(sqlite3_last_insert_rowid(db));

    stmt = nullptr;
    if (sqlite3_prepare_v2(db,
        "INSERT INTO submission_versions(submission_id,version_number,content,is_late) VALUES(?,1,?,0);",
        -1, &stmt, nullptr) != SQLITE_OK) throw std::runtime_error(sqlite3_errmsg(db));
    sqlite3_bind_int(stmt, 1, submissionId);
    const std::string content = "Demonstration submission content";
    sqlite3_bind_text(stmt, 2, content.c_str(), -1, SQLITE_TRANSIENT);
    if (sqlite3_step(stmt) != SQLITE_DONE) {
        sqlite3_finalize(stmt);
        throw std::runtime_error(sqlite3_errmsg(db));
    }
    sqlite3_finalize(stmt);
    notifications_.notifyUser(2, "A student submitted work for C++ Basics Assignment.");

    const double rawMark = 80.0;
    const double finalMark = penalty_.finalMark(rawMark, 100.0, 1);
    stmt = nullptr;
    if (sqlite3_prepare_v2(db,
        "INSERT INTO marks(submission_id,raw_mark,final_mark,feedback,marked_by_user_id) VALUES(?,?,?,?,2);",
        -1, &stmt, nullptr) != SQLITE_OK) throw std::runtime_error(sqlite3_errmsg(db));
    sqlite3_bind_int(stmt, 1, submissionId);
    sqlite3_bind_double(stmt, 2, rawMark);
    sqlite3_bind_double(stmt, 3, finalMark);
    const std::string feedback = "Good structure. Review input validation.";
    sqlite3_bind_text(stmt, 4, feedback.c_str(), -1, SQLITE_TRANSIENT);
    if (sqlite3_step(stmt) != SQLITE_DONE) {
        sqlite3_finalize(stmt);
        throw std::runtime_error(sqlite3_errmsg(db));
    }
    sqlite3_finalize(stmt);
    runSql(db, ("UPDATE submissions SET status='Marked' WHERE submission_id=" +
                std::to_string(submissionId) + ";").c_str());
    audit_.recordMarkChange(submissionId, 2, std::nullopt, finalMark, "Initial marking");
    notifications_.notifyUser(3, "Marks are ready for departmental moderation.");

    // Simulate HoD moderation and release, then notify student.
    stmt = nullptr;
    if (sqlite3_prepare_v2(db,
        "UPDATE marks SET moderated_by_user_id=3, released=1 WHERE submission_id=?;",
        -1, &stmt, nullptr) != SQLITE_OK) throw std::runtime_error(sqlite3_errmsg(db));
    sqlite3_bind_int(stmt, 1, submissionId);
    if (sqlite3_step(stmt) != SQLITE_DONE) {
        sqlite3_finalize(stmt);
        throw std::runtime_error(sqlite3_errmsg(db));
    }
    sqlite3_finalize(stmt);
    runSql(db, ("UPDATE submissions SET status='Released' WHERE submission_id=" +
                std::to_string(submissionId) + ";").c_str());
    notifications_.notifyUser(1, "Your mark has been released. Mark: " + std::to_string(finalMark) +
                                 "/100. Feedback: " + feedback);

    std::cout << "\nDemo workflow complete.\n"
              << "Submission ID: " << submissionId << '\n'
              << "Raw mark: " << rawMark << "/100\n"
              << "Late penalty: 10 marks\n"
              << "Final mark: " << finalMark << "/100\n"
              << "Status: Released\n"
              << "Audit log and notifications saved in lms.db\n";
}
